import type { ComponentAssetMetadata, ComponentRobotId, Vector3Tuple } from './types';
import { mintRuntimeUrl, type MintRuntimeAssetKey } from '../mintRuntimeUrls';

const geometry = (triangles: number): ComponentAssetMetadata['geometry'] => ({
  nodes: 1,
  meshes: 1,
  primitives: 1,
  triangles,
  materials: 1,
  textures: 3,
  images: 3,
  skins: 0,
  animations: 0,
});

const component = <const Role extends string>(
  robotId: ComponentRobotId,
  role: Role,
  filename: string,
  evidencePath: ComponentAssetMetadata['evidencePath'],
  byteSize: number,
  sha256: string,
  triangles: number,
  min: Vector3Tuple,
  max: Vector3Tuple,
): ComponentAssetMetadata<Role> => ({
  role,
  publicUrl: mintRuntimeUrl(`component/${robotId}/${filename}` as MintRuntimeAssetKey),
  filePath: `public/models/components/${robotId}/${filename}.glb`,
  evidencePath,
  byteSize,
  sha256,
  geometry: geometry(triangles),
  localBounds: { min, max },
});

