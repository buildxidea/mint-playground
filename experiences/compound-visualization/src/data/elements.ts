/** Look up an element by symbol; case-insensitive, tolerant of unknowns. */
export function getElement(symbol: string): Element {
  if (!symbol) return UNKNOWN;
  const key = symbol[0].toUpperCase() + symbol.slice(1).toLowerCase();
  return BY_SYMBOL.get(key) ?? BY_SYMBOL.get(symbol) ?? UNKNOWN;
}

