/**
 * Phase of an element at a given temperature in kelvin. Returns "unknown" when
 * the transition points are not known (most superheavy elements).
 */
export function stateAt(el: Element, kelvin: number): MatterState {
  if (el.meltingPoint == null || el.boilingPoint == null) return "unknown";
  if (kelvin < el.meltingPoint) return "solid";
  if (kelvin < el.boilingPoint) return "liquid";
  return "gas";
}

